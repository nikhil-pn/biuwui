// Writes scripts/lib/abi.ts from the Foundry artifacts, so the scripts, relayer, bot and app share one ABI.
import { readFileSync, writeFileSync } from "node:fs";
const pick = (name) => JSON.parse(readFileSync(`out/${name}.sol/${name}.json`, "utf8")).abi;
const out = `// Generated by scripts/gen-abi.mjs from the Foundry artifacts. Do not edit; run \`npm run abi\`.
export const circleAbi = ${JSON.stringify(pick("SovereignCircle"), null, 2)} as const;

export const factoryAbi = ${JSON.stringify(pick("SovereignFactory"), null, 2)} as const;
`;
writeFileSync("scripts/lib/abi.ts", out);
console.log("wrote scripts/lib/abi.ts");
